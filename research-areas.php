<p>
The technology based on solid oxide fuel cells (SOFCs) is demonstrated to be the most efficient in generating clean energy. This solid-state electrochemical device with no moving parts can show efficiency > 80% (with cogeneration) in converting the chemical energy of the fuels and oxidants to electrical energy. Owing to its high-temperature operation (~1000&deg;C), it can also run on a wide range of fuels such as H<sub>2</sub>, syngas, biogas, natural gas, CO, CO<sub>2</sub>, landfill waste, etc. However, this also means requiring expensive and specialized component materials to withstand the stringent environment for a long duration. It has been realized that the successful adoption of SOFC technology, especially for stationary and residential electrical power generation, is only possible when the operating temperature is lowered to an intermediate temperature range (500-850&deg;C) without reducing the performance output. This necessitates the development of innovative materials with improved functionalities and more affordable costs. <br>
Our research group focuses on the development of materials for solid electrolyte and electrodes. For the electrolyte, we characterize the ionic conductivity and study its correlation with the structure, chemistry and processing parameters of several oxygen-ion conductors based on CeO<sub>2</sub>, ZrO<sub>2</sub>, NBT, etc. We also investigate the ASR behaviour of composites based on SrMoO<sub>3</sub> and SrFeO<sub>3</sub> for the electrode application in SOFCs.  Efforts are made to fabricate the prototype of SOFCs using the novel materials and test them in a typical operating condition.</p>
