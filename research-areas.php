<p>
Rechargeable batteries convert chemical energy into electric energy and vice-versa through reversible faradaic redox reactions. Initially, Li-ion batteries (LIBs) became hugely popular because of their efficient performance and higher rate capabilities.  LIBs currently power most of the consumer electronics in the market.  However, the high cost and limited availability of Li mineral resources have driven research to look into other alternatives.  Na-ion batteries (NIBs) are considered next-generation batteries as they promise to become a low-cost storage option for future electric grids as intercalation chemistry in sodium and lithium are similar.   Besides, the Na element is the sixth most abundant element on earth crust and is readily available.  <br>
Our research group focuses on designing materials for all-solid-state NIBs.  All-solid-state NIBs possesses solid electrolyte and thus addresses the serious safety issues associated with liquid organic electrolytes.  We study the process-structure-property correlations in doped NASICON-type oxides necessary to rationally design the high sodium-ion conductive materials for solid electrolyte applications.  Further, our group also investigate oxide-based cathodes for NIBs.  Our research laboratory has the facility to fabricate and electrochemically test the performance of coin cells for batteries application.
</p>
