			<h3 style="background: #f1f1f1; color: royalblue; padding:10px; letter-spacing:1.5px; text-shadow: 2px 2px 3px #fff;"><strong>Supercapacitors</strong></h3>
			<hr>

<p>
Supercapacitors (SCs) are considered as a complimentary energy storage system to batteries, which exhibit superior energy density than conventional capacitors and higher power density than batteries. The long cycle life of SCs has driven their usage in automobiles, electric locomotives, smart phones, etc.   To date, carbon based double layer SCs are commercialized displaying high power density, however, their limited energy density remains a constraint. Later, pseudocapacitors came into picture involving redox reactions driven charge storage mechanism. The mechanism provides substantial increment in the energy density of the order of ~10 or more. Our group's research focuses on the development of novel strategies for the fabrication of advanced supercapacitors. The work involves:<br>
<ul>
<li>	Synthesizing new electrode materials (oxides/chalcogenides/phosphides) with intriguing high surface area morphologies</li>
<li>	Stabilization of freestanding binder-free electrodes</li>
<li>	Electrolyte optimization for enhanced voltage window using redox additives</li>
<li>	Device performance optimization at ambient and non-ambient conditions by synergistic correlation of electrodes and electrolytes redox chemistry</li>
</ul>

</p><br>
